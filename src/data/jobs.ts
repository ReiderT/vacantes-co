/** Calendar-day distance from the scrape. Negative-free; null when the portal gave no date. */
export function daysAgo(publishedAt: string | null): number | null {
  if (!publishedAt) return null
  const then = Date.parse(`${publishedAt}T00:00:00Z`)
  const reference = Date.parse(`${REFERENCE_DATE}T00:00:00Z`)
  if (Number.isNaN(then)) return null
  return Math.round((reference - then) / 86_400_000)
}

export const WEEK_DAYS = 7
export const MONTH_DAYS = 30

export function isThisWeek(job: Job): boolean {
  const days = daysAgo(job.publishedAt)
  return days !== null && days >= 0 && days <= WEEK_DAYS
}

/** The profile's core signal: firmware / embedded / PCB / automation work. */
const FIRMWARE_PATTERN = /firmware|embebid|pcb|automatiz|\bc\+\+\b|iot|mecatr/i

export function isFirmware(job: Job): boolean {
  return FIRMWARE_PATTERN.test(`${job.title} ${job.stack.join(' ')}`)
}

